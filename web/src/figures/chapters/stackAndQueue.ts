// ── Linked-list helpers ───────────────────────────────────────────────

interface LNode {
  id: string;
  value: number;
  cx: number;
  tone?: Tone;
  dim?: boolean;
  ring?: boolean;
}

/**
 * A row of list nodes with `next` arrows (and `prev` arrows for a doubly linked list).
 * `edges` lists [from, to] pairs by id; `dimEdges` fades some of them.
 */
function listRow(nodes: LNode[], y: number, edges: [string, string, Tone?][], opts: { doubly?: boolean; dimEdges?: string[] } = {}) {
  const circles = new Map<string, BoxNode>();
  for (const n of nodes) {
    const item: ListItem = { id: n.id, value: n.value, tone: n.tone ?? 'ok', dim: n.dim, ring: n.ring };
    circles.set(n.id, listNode(item, n.cx, y, 20));
  }
  const out: SceneNode[] = [...circles.values()];
  for (const [a, b, tone] of edges) {
    const ca = circles.get(a)!;
    const cb = circles.get(b)!;
    const dim = opts.dimEdges?.includes(`${a}>${b}`);
    if (opts.doubly) {
      // `next` above the center line, `prev` below it.
      const forward = cb.x > ca.x;
      const off = forward ? -5 : 5;
      out.push(link(`e:${a}>${b}`, { ...ca, y: ca.y + off }, { ...cb, y: cb.y + off }, { tone, dim }));
    } else {
      out.push(link(`e:${a}>${b}`, ca, cb, { tone, dim }));
    }
  }
  return out;
}

